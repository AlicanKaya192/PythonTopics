# Öncelikle değişkenleri ele alacağız. Peki değişken nedir? 
# Değişken, bellekte bir değer tutan bir yerdir. Sürekli değişen kavramlara, terimlere değişken denir.

# Değer atamak istediğimiz zaman = sembolünü kullanırız. 
# print() fonksiyonu ile değişkenleri ekrana yazdırırız.

# Python'da temel matematiksel işlemler şunlardır:
# + : Toplama
# - : Çıkarma
# * : Çarpma
# / : Bölme
# ** : Üs alma
# % : Mod alma

# Toplama işlemi
topla = 2 + 2

print(topla)

# Çarpma işlemi
carpma = 2 * 2

print(carpma)

# Çıkarma işlemi
cikarma = 2 - 2

print(cikarma)

# Bölme işlemi
bolme = 2 / 2

print(bolme)

# Üs alma işlemi
us_alma = 2 ** 2

print(us_alma)

# Mod alma işlemi
mod_alma = 2 % 2

print(mod_alma)

d_yili = 2001
yil = 2026

yas = yil - d_yili

print(yas)
# yas değişkeni yıl ve d_yili değişkenlerinin değerleri çıkarılarak hesaplandı.
# Bu işlem pythonda "aritmetiksel işlem" olarak adlandırılır.

print(type(yas))
# type() fonksiyonu ile değişkenin veri tipini öğreniriz.

sayi = 4000
print(float(sayi))
# Burada int değişkeni float ifadeye çevirdik. Böylece int değişkeni float ifadeye çevirebiliriz. 
# Float ifade nedir ? Float ifade ondalıklı sayıları temsil eder.

sayi = 4000.0
print(sayi)
# Burada float değişkeni ekrana yazdırıldı.