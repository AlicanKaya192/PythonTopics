# Operatörler nedir?
# Operatörler matematiksel ifadeleri hesaplamak için kullanılır.

# Operatörler
# + Toplama
# - Çıkarma
# * Çarpma
# / Bölme
# % Mod alma
# ** Üst alma

x = 5
y = 10

toplam = x + y

print(toplam)
# Bu ilkel bir yöntem :D.

x += y
print(x)
# Bu yöntem daha pratik :D.
# += operatörü ile x = x + y ifadesini yazabiliriz.
# Önce y değerini x'e ekliyoruz sonra x'e atıyoruz.
# Aynı şekilde -=, *=, /=, %=, **= operatörlerini de kullanabiliriz.